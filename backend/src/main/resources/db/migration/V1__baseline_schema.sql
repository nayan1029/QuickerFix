create table departments (
    id bigint generated by default as identity primary key,
    name varchar(255) not null unique,
    description varchar(255),
    contact_email varchar(255),
    active boolean not null default true
);

create table users (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    email varchar(255) not null unique,
    password varchar(255) not null,
    phone varchar(255),
    role varchar(32) not null,
    department_id bigint references departments(id),
    enabled boolean not null default true,
    google_id varchar(255) unique,
    created_at timestamp,
    updated_at timestamp
);

create table categories (
    id bigint generated by default as identity primary key,
    name varchar(255) not null unique,
    description varchar(255),
    icon varchar(255),
    department_id bigint references departments(id),
    active boolean not null default true
);

create table reports (
    id bigint generated by default as identity primary key,
    title varchar(255) not null,
    description text,
    category_id bigint not null references categories(id),
    citizen_id bigint not null references users(id),
    latitude double precision,
    longitude double precision,
    address varchar(255),
    severity varchar(32),
    status varchar(48),
    priority_score integer,
    upvote_count integer,
    duplicate_count integer,
    marked_as_duplicate boolean not null default false,
    duplicate_of_report_id bigint,
    created_at timestamp,
    updated_at timestamp,
    resolved_at timestamp,
    closed_at timestamp
);

create table assignments (
    id bigint generated by default as identity primary key,
    report_id bigint not null references reports(id),
    worker_id bigint not null references users(id),
    assigned_by_id bigint not null references users(id),
    status varchar(32),
    rejection_reason varchar(255),
    assigned_at timestamp,
    accepted_at timestamp,
    completed_at timestamp
);

create table attachments (
    id bigint generated by default as identity primary key,
    report_id bigint not null references reports(id),
    uploaded_by_id bigint not null references users(id),
    file_name varchar(255) not null,
    file_url varchar(255) not null,
    file_type varchar(255),
    file_size bigint,
    is_resolution_proof boolean not null default false,
    uploaded_at timestamp
);

create table comments (
    id bigint generated by default as identity primary key,
    report_id bigint not null references reports(id),
    author_id bigint not null references users(id),
    content varchar(1000) not null,
    created_at timestamp,
    updated_at timestamp
);

create table ratings (
    id bigint generated by default as identity primary key,
    report_id bigint not null unique references reports(id),
    citizen_id bigint not null references users(id),
    score integer not null,
    comment varchar(255),
    created_at timestamp
);

create table status_history (
    id bigint generated by default as identity primary key,
    report_id bigint not null references reports(id),
    changed_by_id bigint not null references users(id),
    old_status varchar(48),
    new_status varchar(48) not null,
    remark varchar(255),
    changed_at timestamp
);

create table notifications (
    id bigint generated by default as identity primary key,
    recipient_id bigint not null references users(id),
    title varchar(255) not null,
    message varchar(255) not null,
    type varchar(48),
    read boolean not null default false,
    related_report_id bigint,
    created_at timestamp
);

create table chat_messages (
    id bigint generated by default as identity primary key,
    report_id bigint not null references reports(id),
    sender_id bigint not null references users(id),
    recipient_id bigint not null references users(id),
    content varchar(1000) not null,
    read boolean not null default false,
    created_at timestamp not null
);

create table announcements (
    id bigint generated by default as identity primary key,
    title varchar(255) not null,
    content text not null,
    created_by_id bigint not null references users(id),
    scope varchar(255) not null,
    target_district_id bigint,
    target_category_id bigint,
    priority varchar(255) not null,
    created_at timestamp not null,
    expires_at timestamp
);

create table announcement_reads (
    id bigint generated by default as identity primary key,
    announcement_id bigint not null references announcements(id),
    user_id bigint not null references users(id),
    read_at timestamp not null,
    constraint uk_announcement_reads_announcement_user unique (announcement_id, user_id)
);


