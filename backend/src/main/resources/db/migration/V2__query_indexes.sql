create table authority_contacts (
    id bigint generated by default as identity primary key,
    authority_name varchar(120) not null,
    service_type varchar(40) not null,
    phone varchar(40), alternate_phone varchar(40), email varchar(160), address varchar(240),
    state varchar(80) not null, district varchar(100), coverage varchar(24) not null,
    instructions varchar(1200), official_source_url varchar(500), verified_at date,
    emergency boolean not null default false, active boolean not null default true
);

create table duplicate_links (
    id bigint generated by default as identity primary key,
    report_id bigint not null unique references reports(id),
    canonical_report_id bigint not null references reports(id),
    linked_by_id bigint not null references users(id),
    note varchar(500), linked_at timestamp not null
);

create table triage_decisions (
    id bigint generated by default as identity primary key,
    report_id bigint not null references reports(id),
    reviewer_id bigint not null references users(id),
    suggested_category_id bigint not null,
    suggested_category_name varchar(120) not null,
    suggested_severity varchar(32) not null,
    confidence double precision not null,
    source varchar(80) not null,
    chosen_category_id bigint not null,
    chosen_severity varchar(32) not null,
    note varchar(500), reviewed_at timestamp not null
);

create index idx_reports_queue on reports (status, priority_score desc, created_at desc);
create index idx_reports_status_created on reports (status, created_at desc);
create index idx_reports_category_created on reports (category_id, created_at desc);
create index idx_reports_category_status_duplicate_created on reports (category_id, status, marked_as_duplicate, created_at desc);
create index idx_reports_citizen_created on reports (citizen_id, created_at desc);
create index idx_reports_location on reports (latitude, longitude);
create index idx_assignments_worker_status on assignments (worker_id, status, assigned_at desc);
create index idx_assignments_report on assignments (report_id);
create index idx_status_history_report_time on status_history (report_id, changed_at);
create index idx_comments_report_time on comments (report_id, created_at);
create index idx_notifications_recipient_read_time on notifications (recipient_id, read, created_at desc);
create index idx_announcement_reads_user_time on announcement_reads (user_id, read_at desc);
create index idx_announcements_scope_priority_expiry on announcements (scope, priority, expires_at);
create index idx_chat_messages_report_time on chat_messages (report_id, created_at);
create index idx_duplicate_links_canonical on duplicate_links (canonical_report_id);
create index idx_triage_decisions_report_time on triage_decisions (report_id, reviewed_at desc);
create index idx_authority_contacts_location on authority_contacts (state, district, active, service_type);
